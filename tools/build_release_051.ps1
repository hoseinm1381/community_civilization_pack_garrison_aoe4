param([switch]$VerifyOnly,[switch]$PackageOnly,[string]$Label=('r'+(Get-Date -Format 'yyMMddHHmmss')))
$ErrorActionPreference='Stop'
$root051=Split-Path $PSScriptRoot -Parent
$cfg051=Get-Content -LiteralPath (Join-Path $root051 'workspace.json') -Raw | ConvertFrom-Json
if ($Label -notmatch '^r[a-z0-9-]{2,15}$') { throw 'Use a fresh run label.' }
if ($VerifyOnly -and $PackageOnly) { throw 'Choose one stage.' }
function Invoke051 { param([string[]]$Arguments) & $cfg051.blender_python -B @Arguments; if ($LASTEXITCODE -ne 0) { throw "051 stage failed: $Arguments" } }
$location051=Get-Location
try {
 Set-Location -LiteralPath $root051
 Invoke051 -Arguments @('tools/release_051/freeze.py','--verify')
 if ($VerifyOnly) {
  Invoke051 -Arguments @('tools/release_051/release.py','verify')
  Invoke051 -Arguments @('tools/release_051/checks.py',$Label)
 } else {
  if (-not $PackageOnly) {
   # Qualified 051 asset receipts are durable inputs, not regenerated by old helpers.
   Invoke051 -Arguments @('tools/release_051/traps.py','apply')
   Invoke051 -Arguments @('tools/release_051/native.py','compile',$Label)
   Invoke051 -Arguments @('tools/release_051/release.py','compose',$Label)
   Invoke051 -Arguments @('tools/release_051/reference.py',$Label)
  }
  Invoke051 -Arguments @('tools/release_051/release.py','package',$Label)
  Invoke051 -Arguments @('tools/release_051/dependency_closure.py')
  Invoke051 -Arguments @('tools/release_051/finalize.py')
  Invoke051 -Arguments @('tools/release_051/report.py')
 }
} finally { Set-Location -LiteralPath $location051 }
