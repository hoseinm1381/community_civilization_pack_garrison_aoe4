"""Generate Vietnam's conditional prematch roster from editable blueprints.

The mode RDO intentionally has an empty unconditional precache list. Restoring
that list would defeat the human-roster loading policy.
"""

from pathlib import Path
import xml.etree.ElementTree as ET


ROOT = Path(__file__).resolve().parents[1]
RDO = ROOT / "assets/scar/winconditions/VietnamMode.rdo"
OUTPUT = ROOT / "assets/scar/vietnam/prematch_precache.scar"
PREFIX = "a743d7d1d7534cf78817e29d8ded7366:"


def names(root, kind):
    result = set()
    for item in root.iter("DataObject"):
        if item.get("Type") != kind:
            continue
        refs = [node.get("Value", "") for node in item.iter("DataProperty") if node.get("Name") == "m_fileName"]
        if len(refs) != 1:
            raise ValueError(f"Expected one blueprint in {kind}: {refs}")
        if refs[0].startswith(PREFIX):
            result.add(refs[0])
    return sorted(result)


def table(values):
    return "{\n" + "".join(f'    "{name}",\n' for name in values) + "}"


def main():
    base = ROOT / "assets/attrib/instances"
    entities = sorted(PREFIX + p.stem for p in (base / "ebps").rglob("vn_*.xml"))
    squads = sorted(PREFIX + p.stem for p in (base / "sbps").rglob("vn_*.xml"))
    if not entities or not squads:
        raise ValueError("No private Vietnam blueprints found in editable source")
    output = f'''-- Generated by tools/generate_prematch_precache.py from editable source.
-- Selection occurs after loading, so every private Vietnam blueprint must be ready
-- even when the player later chooses ordinary China.
local entities = {table(entities)}
local squads = {table(squads)}

function VietnamPrecache_Init()
    if not CCPLoading_Required("chinese") then
        print("CCP_PRECACHE_SKIP family=vietnam")
        return
    end
    CCPLoading_Shared()
    for _, name in ipairs(entities) do
        if EBP_Exists(name) then
            Scar_PrecachePrematchResource(BP_GetEntityBlueprint(name))
        else
            print("VIETNAM_V2_PRECACHE_MISSING_ENTITY " .. name)
        end
    end
    for _, name in ipairs(squads) do
        if SBP_Exists(name) then
            Scar_PrecachePrematchResource(BP_GetSquadBlueprint(name))
        else
            print("VIETNAM_V2_PRECACHE_MISSING_SQUAD " .. name)
        end
    end
end

Scar_AddInit(VietnamPrecache_Init)
'''
    OUTPUT.write_text(output, encoding="utf-8", newline="\n")
    print(f"Prematch precache: {len(entities)} entities, {len(squads)} squads")


if __name__ == "__main__":
    main()
